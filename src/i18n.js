// TT below is a big flat Malay->target-language lookup, one map per
// SUPPORTED_LANGUAGES code; short common words like "hari" (day)
// legitimately recur as a key across many unrelated phrases with the same
// translation each time -- harmless in practice (object literals just keep
// the last, identical, value) but tsc's duplicate-key check can't tell
// "harmless repeat" from "actually conflicting" without per-entry review,
// and this file has no logic worth type-checking anyway.
/* ============================= i18n =============================
   Two layers:
   - I18N/t(): a small, fully-translated set of ~36 keys (nav labels, page
     titles, common buttons, the login screen) -- the app's own "chrome",
     visible on every single screen regardless of which view is open. Every
     supported language (see SUPPORTED_LANGUAGES below) has a complete,
     hand-written entry for all of these.
   - TT/tt(): a much larger (~300 entries) Malay-keyed lookup used for body
     text scattered across every individual view (form labels, help text,
     toast/confirm messages) -- also now fully translated per language, not
     just English. tt() looks up TT[state.displayLanguage] first, then
     falls back to TT.en, then to the original Malay text itself, so a
     stray untranslated string degrades to English rather than showing
     nothing or breaking.
   Neither layer covers the >1,000 other hardcoded bilingual ternaries
   (`state.language==='en'?'X':'Y'`) spread throughout every view file --
   those still only know ms/en (state.language, forced to 'en' for any
   other displayLanguage -- see setDisplayLanguage() below) and fall back
   to English for the other 9 languages. Migrating each of those call
   sites to route through tt() instead is a much larger, separate,
   mechanical effort not attempted in this pass.
*/
