// Only Malay gets its own literal text back -- every OTHER language falls
// back TT[displayLanguage] -> TT.en -> the raw Malay key itself, so a
// translation missing from one specific language's map still shows
// English rather than nothing. See the file header comment for the
// remaining >1,000 hardcoded ternaries this layer doesn't cover yet.
function tt(msText){
  if(state.displayLanguage==='ms') return msText;
  const dict = TT[state.displayLanguage];
  return (dict && dict[msText]) || TT.en[msText] || msText;
}
